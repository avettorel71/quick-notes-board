const DICTS: Record<QnbLang, Dict> = { it, en };

export function t(lang: QnbLang, key: string, vars?: Record<string, string>): string {
	const dict = DICTS[lang] || DICTS.it;
	let str = dict[key] ?? DICTS.it[key] ?? key;
	if (vars) {
		for (const [k, v] of Object.entries(vars)) {
			str = str.split(`{${k}}`).join(v);
		}
	}
	return str;
}
